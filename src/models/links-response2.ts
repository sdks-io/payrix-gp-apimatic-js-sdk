export type LinksResponse2 = {
  /** A unique identifier for the merchant set by Global Payments. */
  merchantId?: string;
  /** A meaningful label for the merchant set by Global Payments. */
  merchantName?: string;
  /** A unique identifier for the merchant account set by Global Payments. */
  accountId?: string;
  /** A meaningful label for the merchant account set by Global Payments. */
  accountName?: string;
  /** A unique identifier generated by Global Payments to identify the link. */
  id?: string;
  /** The URL that the customer should be redirected to in order to make their payment. */
  url?: string;
  /**
   * The overall status of the instance of the resource.The overall status of the instance of the
   * resource. *`ACTIVE` - When a link is initially created it is in an ACTIVE status waiting to be
   * paid. Links can only be paid when they are in a ACTIVE status. *`CLOSED` - When a multi use
   * link is paid it max number of time it is updated to be CLOSED automatically. A CLOSED link
   * cannot be paid again. *`PAID` - When a single use link is paid once then its status is updated
   * to PAID automatically. A PAID link cannot be paid again. *`INACTIVE` - An INACTIVE link is a
   * link that you have marked as INACTIVE. Links can be manually updated / toggled between ACTIVE
   * and INACTIVE using the PATCH request. A link cannot be paid while it is in an INACTIVE state.
   * *`EXPIRED` - An EXPIRED link is a link the expiration_date set in the request is in the past.
   */
  status?: StatusLinksStatus;
  /** GP API specific label that indicates the type resource an instance is. */
  type?: TypeLinksType;
  /** Indicates whether the link can be used once or multiple times */
  usageMode?: UsageModeLinksUsageMode;
  /** The number of the times that the link can be used or paid. */
  usageLimit?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  /** A descriptive name for the link. This will be visible to the customer on the payment page. */
  name?: string;
  /**
   * A detailed description of your link that will be visible to the customer on the payment page.
   */
  description?: string;
  /**
   * Indicates if you want to capture the customers shipping information on the hosted payment page.
   * If you enable this field you can also set an optional shipping fee in the shipping_amount.
   */
  shippable?: ShippableLinksShippable;
  /** Indicates the cost of shipping when the shippable field is set to YES. */
  shippingAmount?: string;
  /** Indicates the number of times that a link has already been successfully paid. */
  usageCount?: string;
  /** The number of times a link has been viewed. */
  viewedCount?: string;
  /**
   * Indicates the date and time after which the link can no longer be used or paid. Please note
   * that the timezone is in UTC+0
   */
  expirationDate?: string;
  /**
   * Base64 encoded images of the products / services that you want to display on the hosted payment
   * page.
   */
  images?: string[];
  transactions?: Transactions2[];
  action?: Action112;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

