import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  actionTransactionsInternalSchema,
  actionTransactionsSchema,
  type ActionTransactions,
} from "./action-transactions.js";
import {
  channelAuthenticationsChannelSchema,
  type ChannelAuthenticationsChannel,
} from "./channel-authentications-channel.js";
import { device8InternalSchema, device8Schema, type Device8 } from "./device8.js";
import {
  statusTransactionsDeviceStatusSchema,
  type StatusTransactionsDeviceStatus,
} from "./status-transactions-device-status.js";
import {
  typeTransactionsDeviceTypeSchema,
  type TypeTransactionsDeviceType,
} from "./type-transactions-device-type.js";

export type DeviceSyncResponse = {
  /** A unique identifier generated by Global Payments to identify the device synchronization. */
  id?: string;
  /** Time indicating when the transaction was created in ISO-8601 format. */
  timeCreated?: Date;
  /**
   * Indicates the type of physical device used to process the transaction.
   * * `TERMINAL` - A device used to prompt the payer to enter their payment method credentials to
   *   process a transaction.
   * * `MOBILE_PHONE` - A mobile phone was used as the processing device.
   * * `MOBILE_POS` - Mobile device with no add-on hardware.
   * * `MOBILE_POS_PLUS_HARDWARE` - Mobile device with add-on hardware.
   * * `MOBILE_POS_PLUS_DONGLE` - Dedicated mPOS Terminal with PCI compliant dongle.
   * * `DONGLE_PIN` - Dongle with software-based application that supports PIN entry on glass.
   * * `MOBILE_POS_PIN` - Off the shelf mobile device with software-based application that supports
   *   PIN entry on glass.
   */
  type?: TypeTransactionsDeviceType;
  /**
   * Indicates where the currency conversion is in its lifecycle * `AVAILABLE` - A currency
   * conversion is available. The next step is to offer the conversion details to the end user. *
   * `NOT_AVAILABLE` - A currency conversion is not available.
   */
  status?: StatusTransactionsDeviceStatus;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific merchant. Begins with the three letters,
   * MER.
   */
  merchantId?: string;
  /** A meaningful label that better identifies the merchant. */
  merchantName?: string;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific account. Begins with the three letters,
   * TRA.
   */
  accountId?: string;
  /** A meaningful label that better identifies the account. */
  accountName?: string;
  /**
   * Describes whether the transaction was processed in a face to face(CP) scenario or a Customer
   * Not Present (CNP) scenario.
   * * `CP` - A Customer Present transaction is when the payer and the merchant are in direct face
   *   to face contact when exchanging payment method information to fulfill a transaction. e.g. in
   *   a store and paying at the counter that is attended by a clerk.
   * * `CNP` - A Customer NOT Present transaction is when the payer and the merchant are not
   *   together when exchanging payment method information to fulfill a transaction. e.g. a
   *   transaction executed from a merchant's website or over the phone
   */
  channel?: ChannelAuthenticationsChannel;
  /**
   * This is the country the merchant is domiciled in. For example, if the merchant is based in
   * Canada it must be set to CA.if the merchant is based in England it must be set to GB.if the
   * merchant is based in USA it must be set to US.The country in ISO-3166-1(alpha-2 code) format.
   */
  country?: string;
  device?: Device8;
  /** Information about the Action executed. */
  action?: ActionTransactions;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const deviceSyncResponseProperties: s.Shape<DeviceSyncResponse> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  type: s.optional(s.lazy(() => typeTransactionsDeviceTypeSchema)),
  status: s.optional(s.lazy(() => statusTransactionsDeviceStatusSchema)),
  merchantId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  channel: s.optional(s.lazy(() => channelAuthenticationsChannelSchema)),
  country: s.optional(s.string()),
  device: s.optional(s.lazy(() => device8InternalSchema)),
  action: s.optional(s.lazy(() => actionTransactionsInternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account_id",
    accountName: "account_name",
  },
};

export const deviceSyncResponseInternalSchema: Schema<DeviceSyncResponse> = s.object<DeviceSyncResponse>(
  deviceSyncResponseProperties,
  { additionalProperties: s.json() },
);

export const deviceSyncResponseSchema: Schema<DeviceSyncResponse> = s.lazySchema(() =>
  s.object<DeviceSyncResponse>(
    {
      ...deviceSyncResponseProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      country: s.optional(s.string().check(s.minLength(2), s.maxLength(2))),
      device: s.optional(s.lazy(() => device8Schema)),
      action: s.optional(s.lazy(() => actionTransactionsSchema)),
    },
    { additionalProperties: s.json() },
  ),
);
