import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { action31InternalSchema, action31Schema, type Action31 } from "./action31.js";
import {
  paymentMethodFundsPaymentMethodSchema,
  type PaymentMethodFundsPaymentMethod,
} from "./payment-method-funds-payment-method.js";
import { provider1InternalSchema, provider1Schema, type Provider1 } from "./provider1.js";
import { statusFundsStatusSchema, type StatusFundsStatus } from "./status-funds-status.js";
import { typeFundsTypeSchema, type TypeFundsType } from "./type-funds-type.js";

export type FundsResponse3 = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future.
   */
  id?: string;
  /** GP API specific created time indicating when the instance of the resource was created. */
  timeCreated?: Date;
  /** GP API specific last updated time when the instance of the resource was last updated. */
  timeLastUpdated?: Date;
  /**
   * Indicates whether to debit the amount to a bank account/payout card, or credit the amount to
   * the Global Funds Management account.
   */
  type?: TypeFundsType;
  /** Indicates where a resource object is in it's lifecycle. */
  status?: StatusFundsStatus;
  /**
   * The amount that should be credited or debited. It is always represented in the lowest
   * denomiation of the related currency.
   */
  amount?: string;
  /** The currency of the amount in ISO-4217(alpha-3) */
  currency?: string;
  /**
   * The payment method available to create transactions with.
   * * `BANK_TRANSFER` - Indicates to transfer funds to or from the connected payout bank account.
   *
   *  * `CARD` - Indicates to transfer funds to the "Funds Payout Card."
   */
  paymentMethod?: PaymentMethodFundsPaymentMethod;
  /**
   * A unique identifier for the merchant set by Global Payments.
   *
   * @default "MER_880c34767b184d5e82b10e767201e648"
   */
  merchantId?: string;
  /** This is a label to identify the merchant */
  merchantName?: string;
  /** The account identifier for the account that sent a transfer. */
  accountId?: string;
  /** The account name for the account that sent a transfer. */
  accountName?: string;
  provider?: Provider1;
  /** The action reference of the initial action related to the funding event. */
  actionCreateId?: string;
  /** The resource id of the initial funding action referenced. */
  parentResourceId?: string;
  action?: Action31;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const fundsResponse3Properties: s.Shape<FundsResponse3> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  timeLastUpdated: s.optional(s.dateTime()),
  type: s.optional(s.lazy(() => typeFundsTypeSchema)),
  status: s.optional(s.lazy(() => statusFundsStatusSchema)),
  amount: s.optional(s.string()),
  currency: s.optional(s.string()),
  paymentMethod: s.optional(s.lazy(() => paymentMethodFundsPaymentMethodSchema)),
  merchantId: s.defaulted(s.string(), "MER_880c34767b184d5e82b10e767201e648"),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  provider: s.optional(s.lazy(() => provider1InternalSchema)),
  actionCreateId: s.optional(s.string()),
  parentResourceId: s.optional(s.string()),
  action: s.optional(s.lazy(() => action31InternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    timeLastUpdated: "time_last_updated",
    paymentMethod: "payment_method",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account_id",
    accountName: "account_name",
    actionCreateId: "action_create_id",
    parentResourceId: "parent_resource_id",
  },
};

export const fundsResponse3InternalSchema: Schema<FundsResponse3> = s.object<FundsResponse3>(
  fundsResponse3Properties,
  { additionalProperties: s.json() },
);

export const fundsResponse3Schema: Schema<FundsResponse3> = s.lazySchema(() =>
  s.object<FundsResponse3>(
    {
      ...fundsResponse3Properties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      amount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      currency: s.optional(s.string().check(s.minLength(3), s.maxLength(3))),
      merchantId: s.defaulted(
        s.string().check(s.minLength(1), s.maxLength(50)),
        "MER_880c34767b184d5e82b10e767201e648",
      ),
      merchantName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      provider: s.optional(s.lazy(() => provider1Schema)),
      actionCreateId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      parentResourceId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      action: s.optional(s.lazy(() => action31Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
