import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { ephemeralPublicKeySchema, type EphemeralPublicKey } from "./ephemeral-public-key.js";
import {
  sdkInterfaceAuthenticationsMobileDataSdkInterfaceSchema,
  type SdkInterfaceAuthenticationsMobileDataSdkInterface,
} from "./sdk-interface-authentications-mobile-data-sdk-interface.js";
import { sdkUiTypeSchema, type SdkUiType } from "./sdk-ui-type.js";

export type MobileData = {
  /**
   * Indicates the type of interface provided by the mobile SDK to present the challenge to the
   * user.
   */
  sdkInterface?: SdkInterfaceAuthenticationsMobileDataSdkInterface;
  /** Specifies which UI types the SDK supports for challenge screens */
  sdkUiType?: SdkUiType[];
  ephemeralPublicKey?: EphemeralPublicKey;
  /** Defines the maximum time (in minutes) the SDK allows for a challenge interaction. */
  maximumTimeout?: string;
  /** Identifies the SDK vendor and version. */
  referenceNumber?: string;
  /** A unique transaction identifier generated by the SDK. */
  sdkTransReference?: string;
  /** Contains the Base 64 encoded SDK data required for authentication. */
  encodedData?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

export const mobileDataSchema: Schema<MobileData> = s.object<MobileData>(
  {
    sdkInterface: s.optional(s.lazy(() => sdkInterfaceAuthenticationsMobileDataSdkInterfaceSchema)),
    sdkUiType: s.optional(s.array(s.lazy(() => sdkUiTypeSchema))),
    ephemeralPublicKey: s.optional(s.lazy(() => ephemeralPublicKeySchema)),
    maximumTimeout: s.optional(s.string()),
    referenceNumber: s.optional(s.string()),
    sdkTransReference: s.optional(s.string()),
    encodedData: s.optional(s.string()),
    _keysMap: {
      sdkInterface: "sdk_interface",
      sdkUiType: "sdk_ui_type",
      ephemeralPublicKey: "ephemeral_public_key",
      maximumTimeout: "maximum_timeout",
      referenceNumber: "reference_number",
      sdkTransReference: "sdk_trans_reference",
      encodedData: "encoded_data",
    },
  },
  { additionalProperties: s.json() },
);
