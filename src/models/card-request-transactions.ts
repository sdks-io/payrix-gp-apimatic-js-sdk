export type CardRequestTransactions = {
  /**
   * The card number used to authorize the transaction. Also known as PAN (Primary Account Number).
   */
  number?: string;
  /** The 2 digit expiry date month of the card. */
  expiryMonth?: string;
  /** The 2 digit expiry date year of the card. */
  expiryYear?: string;
  /** Data from magnetic stripe of a card. */
  track?: string;
  /**
   * "The number that identifies the track data type. This field is required if the track data is
   * encrypted."
   */
  trackNumber?: string;
  /** The full card tag data for an EMV/chip card transaction. */
  tag?: string;
  /**
   * Indicates if a fallback mechanism was used to obtain the card information when EMV/chip did not
   * work as expected.
   * * `PREV_SUCCESS` - indicates the previous transaction with this card was a success.
   * * `PREV_FAILED` - indicates the previous transaction with this card failed.
   * * `NON_CHIP_TRANSACTION` - indicates this was not a chip transaction.
   * * `UNKNOWN` - indicates the reason is unknown.
   */
  chipCondition?: ChipConditionTransactionsPaymentMethodCardChipCondition;
  /** Contains the pin block info, relating to the pin code the Payer entered. */
  pinBlock?: string;
  /** The key serial number associated with the pin provided. */
  pinKeySerialNumber?: string;
  /** The card providers description of their card product. */
  accountType?: string;
  /** The numeric value printed on the physical card. */
  cvv?: string;
  /**
   * Card Verification Value Indicator sent by the Merchant indicating the CVV availability.
   * * `ILLEGIBLE` - indicates the cvv is present but cannot be read.
   * * `NOT_PRESENT` - indicates the cvv is not present on the card.
   * * `PRESENT` - indicates the cvv is present.
   */
  cvvIndicator?: CvvIndicatorAuthenticationsPaymentMethodCardCvvIndicator;
  /** First line of the address associated with the card. */
  avsAddress?: string;
  /** Postal code of the address associated with the card. */
  avsPostalCode?: string;
  /**
   * Indicates how the card is funded:
   * * `DEBIT` - indicates the card is a debit card where the funds may be present in an account to
   *   fulfill the transaction amount.
   * * `CREDIT` - indicates the card is a credit card where the funds may be available on credit to
   *   the payer to fulfill the transaction amount.
   * * `FOOD_STAMP` - indicates the card is an, Electronic Benefits Transfer, for food stamps.
   * * `CASH_BENEFITS` - indicates the card is an, Electronic Benefits Transfer, for cash benefits.
   * * `PREPAID` - indicates the card is a prepaid card where the funds are loaded to the card
   *   account to fulfill the transaction amount. Unlike a debit card, a prepaid is not linked to a
   *   bank account.
   * * `ELECTRONIC_VOUCHER` - Indicates that card is an electronic voucher which requires a voucher
   *   code and number to fulfil the transaction
   */
  funding?: FundingTransactionsPaymentMethodCardFunding;
  /** Code generated by the card provider when the card is successfully authorized. */
  authcode?: string;
  /** The voucher number associated with the Electronic Voucher card */
  voucherNumber?: string;
  /** The voucher code associated with the Electronic Voucher card */
  voucherCode?: string;
  /** The unique reference created by the brands/schemes to uniquely identify the transaction. */
  brandReference?: string;
  /** The network token provided by the brands as a more secure alternative to the card number. */
  networkToken?: string;
  /** The 2 digit expiry date month of the network token. */
  networkTokenExpiryMonth?: string;
  /** The 2 digit expiry date year of the network token. */
  networkTokenExpiryYear?: string;
  /**
   * The condition that caused the chip or POS reader to fail. When this happens, the POS device
   * offers a fallback option and provides the fallback condition.
   * * `TERMINAL_CONNECTION_ERROR` - Failure due to connection issues.The ICC and terminal could not
   *   exchange EMV data with each other to complete a flow.
   * * `CARD_COMPATIBILITY_ERROR` - Failure due to compatibiliyt issues.The ICC and terminal do not
   *   share a common AID that would have allowed a transaction to happen.
   */
  swipeReason?: SwipeReasonTransactionsPaymentMethodCardSwipeReason;
  /**
   * Indicates whether Payment Account Reference (PAR) should be returned with the authorization,
   * when available
   */
  paymentAccountReferenceMode?: PaymentAccountReferenceModeTransactionsPaymentMethodCardPaymentAccountReferenceMode;
  /** This is the cryptogram that is needed to process a CIT Network Tokenization request */
  cryptogram?: string;
  /**
   * This is the cryptogram eci that is needed to process a CIT Network Tokenization request with
   * 3DSecure
   */
  eci?: string;
  /**
   * The PAN reference identifier for the payment account of the cardholder. Available for Visa and
   * Discover transactions.
   */
  numberReferenceIdentifier?: string;
  /**
   * The data from the magnetic stripe. This may include track 1 and/or track 2. Emulated Track Data
   * can be generated by entering the card details manually using the emulated key board.
   */
  trackEmulated?: string;
  /**
   * Indicates whether Global Payments must decrypt the merchant’s encrypted data to process the
   * transaction.
   */
  decryptionRequired?: DecryptionRequiredTransactionsPaymentMethodCardDecryptionRequired;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

