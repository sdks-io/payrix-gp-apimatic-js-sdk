import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  avsActionTransactionsPaymentMethodCardAvsActionSchema,
  type AvsActionTransactionsPaymentMethodCardAvsAction,
} from "./avs-action-transactions-payment-method-card-avs-action.js";
import {
  avsAddressResultAuthenticationsPaymentMethodCardAvsAddressResultSchema,
  type AvsAddressResultAuthenticationsPaymentMethodCardAvsAddressResult,
} from "./avs-address-result-authentications-payment-method-card-avs-address-result.js";
import {
  avsPostalCodeResultAuthenticationsPaymentMethodCardAvsPostalCodeResultSchema,
  type AvsPostalCodeResultAuthenticationsPaymentMethodCardAvsPostalCodeResult,
} from "./avs-postal-code-result-authentications-payment-method-card-avs-postal-code-result.js";
import {
  brandTransactionsPaymentMethodCardBrandSchema,
  type BrandTransactionsPaymentMethodCardBrand,
} from "./brand-transactions-payment-method-card-brand.js";
import { cardProviderInternalSchema, cardProviderSchema, type CardProvider } from "./card-provider.js";
import {
  currencyTransactionsPaymentMethodCardCurrencySchema,
  type CurrencyTransactionsPaymentMethodCardCurrency,
} from "./currency-transactions-payment-method-card-currency.js";
import {
  cvvResultAuthenticationsPaymentMethodCardCvvResultSchema,
  type CvvResultAuthenticationsPaymentMethodCardCvvResult,
} from "./cvv-result-authentications-payment-method-card-cvv-result.js";
import {
  fundingTransactionsPaymentMethodCardFundingSchema,
  type FundingTransactionsPaymentMethodCardFunding,
} from "./funding-transactions-payment-method-card-funding.js";

export type CardResponseTransactions = {
  /** Masked card number with last 4 digits visible. */
  maskedNumberLast4?: string;
  /**
   * The card EMV tag response data from the card issuer for a contactless or chip card transaction.
   */
  tagResponse?: string;
  /** Code generated by the card provider when the card is successfully authorized. */
  authcode?: string;
  /** Indicates the card brand that issued the card. */
  brand?: BrandTransactionsPaymentMethodCardBrand;
  /** The unique reference created by the brands/schemes to uniquely identify the transaction. */
  brandReference?: string;
  /**
   * The time returned by the card brand indicating when the transaction was processed on the
   * brand's system.
   */
  brandTimeReference?: Date;
  /** The result of the CVV check. */
  cvvResult?: CvvResultAuthenticationsPaymentMethodCardCvvResult;
  /** The name of the issuing bank that issued the card. */
  issuer?: string;
  /**
   * This is the country the card is issued in. It represents the country the card's bank is
   * based.The country in ISO-3166-1(alpha-2 code) format.
   */
  country?: string;
  /** The currency associated with the country of issuing bank. */
  currency?: CurrencyTransactionsPaymentMethodCardCurrency;
  /**
   * Indicates how the card is funded:
   * * `DEBIT` - indicates the card is a debit card where the funds may be present in an account to
   *   fulfill the transaction amount.
   * * `CREDIT` - indicates the card is a credit card where the funds may be available on credit to
   *   the payer to fulfill the transaction amount.
   * * `FOOD_STAMP` - indicates the card is an, Electronic Benefits Transfer, for food stamps.
   * * `CASH_BENEFITS` - indicates the card is an, Electronic Benefits Transfer, for cash benefits.
   * * `PREPAID` - indicates the card is a prepaid card where the funds are loaded to the card
   *   account to fulfill the transaction amount. Unlike a debit card, a prepaid is not linked to a
   *   bank account.
   * * `ELECTRONIC_VOUCHER` - Indicates that card is an electronic voucher which requires a voucher
   *   code and number to fulfil the transaction
   */
  funding?: FundingTransactionsPaymentMethodCardFunding;
  /** The available currency amount on the payment method that can be used for a purchase */
  availableBalance?: string;
  /** The result of the AVS address check. */
  avsAddressResult?: AvsAddressResultAuthenticationsPaymentMethodCardAvsAddressResult;
  /** The result of the AVS postal code check. */
  avsPostalCodeResult?: AvsPostalCodeResultAuthenticationsPaymentMethodCardAvsPostalCodeResult;
  /** The recommended action to be taken by the merchant based on the AVS response. */
  avsAction?: AvsActionTransactionsPaymentMethodCardAvsAction;
  /** The result codes directly from the card issuer. */
  provider?: CardProvider;
  /** Masked network token but last 4 digits of the network token are visible. */
  maskedNetworkTokenLast4?: string;
  /** The 2 digit expiry date month of the network token. */
  networkTokenExpiryMonth?: string;
  /** The 2 digit expiry date year of the network token. */
  networkTokenExpiryYear?: string;
  /**
   * This is the Payment Account Reference (PAR) that is returned by the Issuer when requested and
   * available.
   */
  paymentAccountReference?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const cardResponseTransactionsProperties: s.Shape<CardResponseTransactions> = {
  maskedNumberLast4: s.optional(s.string()),
  tagResponse: s.optional(s.string()),
  authcode: s.optional(s.string()),
  brand: s.optional(s.lazy(() => brandTransactionsPaymentMethodCardBrandSchema)),
  brandReference: s.optional(s.string()),
  brandTimeReference: s.optional(s.dateTime()),
  cvvResult: s.optional(s.lazy(() => cvvResultAuthenticationsPaymentMethodCardCvvResultSchema)),
  issuer: s.optional(s.string()),
  country: s.optional(s.string()),
  currency: s.optional(s.lazy(() => currencyTransactionsPaymentMethodCardCurrencySchema)),
  funding: s.optional(s.lazy(() => fundingTransactionsPaymentMethodCardFundingSchema)),
  availableBalance: s.optional(s.string()),
  avsAddressResult: s.optional(
    s.lazy(() => avsAddressResultAuthenticationsPaymentMethodCardAvsAddressResultSchema),
  ),
  avsPostalCodeResult: s.optional(
    s.lazy(() => avsPostalCodeResultAuthenticationsPaymentMethodCardAvsPostalCodeResultSchema),
  ),
  avsAction: s.optional(s.lazy(() => avsActionTransactionsPaymentMethodCardAvsActionSchema)),
  provider: s.optional(s.lazy(() => cardProviderInternalSchema)),
  maskedNetworkTokenLast4: s.optional(s.string()),
  networkTokenExpiryMonth: s.optional(s.string()),
  networkTokenExpiryYear: s.optional(s.string()),
  paymentAccountReference: s.optional(s.string()),
  _keysMap: {
    maskedNumberLast4: "masked_number_last4",
    tagResponse: "tag_response",
    brandReference: "brand_reference",
    brandTimeReference: "brand_time_reference",
    cvvResult: "cvv_result",
    availableBalance: "available_balance",
    avsAddressResult: "avs_address_result",
    avsPostalCodeResult: "avs_postal_code_result",
    avsAction: "avs_action",
    maskedNetworkTokenLast4: "masked_network_token_last4",
    networkTokenExpiryMonth: "network_token_expiry_month",
    networkTokenExpiryYear: "network_token_expiry_year",
    paymentAccountReference: "payment_account_reference",
  },
};

export const cardResponseTransactionsInternalSchema: Schema<CardResponseTransactions> =
  s.object<CardResponseTransactions>(cardResponseTransactionsProperties, { additionalProperties: s.json() });

export const cardResponseTransactionsSchema: Schema<CardResponseTransactions> = s.lazySchema(() =>
  s.object<CardResponseTransactions>(
    {
      ...cardResponseTransactionsProperties,
      maskedNumberLast4: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      tagResponse: s.optional(s.string().check(s.minLength(1), s.maxLength(500))),
      authcode: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      brandReference: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      issuer: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      country: s.optional(s.string().check(s.minLength(2), s.maxLength(2))),
      provider: s.optional(s.lazy(() => cardProviderSchema)),
      maskedNetworkTokenLast4: s.optional(s.string().check(s.minLength(4), s.maxLength(4))),
      paymentAccountReference: s.optional(s.string().check(s.minLength(1), s.maxLength(35))),
    },
    { additionalProperties: s.json() },
  ),
);
