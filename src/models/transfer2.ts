import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { provider39Schema, type Provider39 } from "./provider39.js";
import { statusTransfersStatusSchema, type StatusTransfersStatus } from "./status-transfers-status.js";
import { typeGetTransfersType4Schema, type TypeGetTransfersType4 } from "./type-get-transfers-type4.js";
import {
  UsableBalanceModeTransfersUsableBalanceMode,
  usableBalanceModeTransfersUsableBalanceModeSchema,
} from "./usable-balance-mode-transfers-usable-balance-mode.js";

export type Transfer2 = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future.
   */
  id?: string;
  /** GP API specific created time indicating when the instance of the resource was created. */
  timeCreated?: string;
  /** GP API specific last updated time when the instance of the resource was last updated. */
  timeLastUpdated?: string;
  /**
   * Indicates the specific action taken.
   *   * `DEBIT` - indicates the action perfomred was a transfer to another merchant.
   *   * `CREDIT` - indicates the action perfomred was a transfer to this merchant.
   */
  type?: TypeGetTransfersType4;
  /**
   * The overall status of the resource.
   *                   * `SUCCESS` - indicates the instant success of of a standalone transfer.
   *                   * `FAILED` - indicates the failure of an instant standalone transfer.
   */
  status?: StatusTransfersStatus;
  /**
   * The amount that is being transferred. Represented in the lowest denomination of the currency
   * (i.e. $100.00 = 10000
   */
  amount?: string;
  /**
   * The balance from which the transfer should pull. The transfer will always use avaialble funds
   * first, and may, as directed by this field, pull from the pending balance.
   *                   * `AVAILABLE_BALANCE` - indicates that a transfer will pull only from
   *                     available funds in the funds management account.
   *                   * `AVAILABLE_AND_PENDING_BALANCE` - indicates the transfer will pull first
   *                     from the available balance, and then from the pending balance of the funds
   *                     management account, if needed.
   *
   * @default UsableBalanceModeTransfersUsableBalanceMode.AvailableBalance
   */
  usableBalanceMode?: UsableBalanceModeTransfersUsableBalanceMode;
  /** A unique identifier for the merchant set by Global Payments. */
  merchantId?: string;
  /** The merchant name of the account that sent the transfer. */
  merchantName?: string;
  /** The account identifier for the account that sent a transfer. */
  accountId?: string;
  /** The account name for the account that sent a transfer. */
  accountName?: string;
  /** The merchant identifier of the account that received the transfer. */
  recipientMerchantId?: string;
  /** The merchant name of the account that received the transfer. */
  recipientMerchantName?: string;
  /** The account identifier for the account that recieved a transfer. */
  recipientAccountName?: string;
  /** The account identifier for the account that recieved a transfer. */
  recipientAccountId?: string;
  /**
   * A label on the GP API platform that further identifies the instance fo the resource. This is
   * intended to be unique but GP API does not polic its uniqueness.
   */
  reference?: string;
  /** The description of the transfer */
  description?: string;
  provider?: Provider39;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const transfer2Properties: s.Shape<Transfer2> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.string()),
  timeLastUpdated: s.optional(s.string()),
  type: s.optional(s.lazy(() => typeGetTransfersType4Schema)),
  status: s.optional(s.lazy(() => statusTransfersStatusSchema)),
  amount: s.optional(s.string()),
  usableBalanceMode: s.defaulted(
    usableBalanceModeTransfersUsableBalanceModeSchema,
    UsableBalanceModeTransfersUsableBalanceMode.AvailableBalance,
  ),
  merchantId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  recipientMerchantId: s.optional(s.string()),
  recipientMerchantName: s.optional(s.string()),
  recipientAccountName: s.optional(s.string()),
  recipientAccountId: s.optional(s.string()),
  reference: s.optional(s.string()),
  description: s.optional(s.string()),
  provider: s.optional(s.lazy(() => provider39Schema)),
  _keysMap: {
    timeCreated: "time_created",
    timeLastUpdated: "time_last_updated",
    usableBalanceMode: "usable_balance_mode",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account-_id",
    accountName: "account_name",
    recipientMerchantId: "recipient_merchant_id",
    recipientMerchantName: "recipient_merchant_name",
    recipientAccountName: "recipient_account_name",
    recipientAccountId: "recipient_account_id",
  },
};

export const transfer2InternalSchema: Schema<Transfer2> = s.object<Transfer2>(transfer2Properties, {
  additionalProperties: s.json(),
});

export const transfer2Schema: Schema<Transfer2> = s.lazySchema(() =>
  s.object<Transfer2>(
    {
      ...transfer2Properties,
      amount: s.optional(s.string().check(s.maxLength(50))),
      accountId: s.optional(s.string().check(s.maxLength(50))),
      accountName: s.optional(s.string().check(s.maxLength(50))),
      recipientAccountId: s.optional(s.string().check(s.maxLength(50))),
      reference: s.optional(s.string().check(s.maxLength(50))),
      description: s.optional(s.string().check(s.maxLength(50))),
    },
    { additionalProperties: s.json() },
  ),
);
