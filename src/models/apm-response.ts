import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { bankAccountSchema, type BankAccount } from "./bank-account.js";
import {
  categoryTransactionsPaymentMethodApmCategorySchema,
  type CategoryTransactionsPaymentMethodApmCategory,
} from "./category-transactions-payment-method-apm-category.js";
import {
  fundStatusTransactionsPaymentMethodApmFundStatusSchema,
  type FundStatusTransactionsPaymentMethodApmFundStatus,
} from "./fund-status-transactions-payment-method-apm-fund-status.js";
import { mandateSchema, type Mandate } from "./mandate.js";
import {
  nextActionTransactionsPaymentMethodApmNextActionSchema,
  type NextActionTransactionsPaymentMethodApmNextAction,
} from "./next-action-transactions-payment-method-apm-next-action.js";
import {
  optionalRedirectTransactionsPaymentMethodApmOptionalRedirectSchema,
  type OptionalRedirectTransactionsPaymentMethodApmOptionalRedirect,
} from "./optional-redirect-transactions-payment-method-apm-optional-redirect.js";
import { provider13InternalSchema, provider13Schema, type Provider13 } from "./provider13.js";
import {
  waitNotificationTransactionsPaymentMethodApmWaitNotificationSchema,
  type WaitNotificationTransactionsPaymentMethodApmWaitNotification,
} from "./wait-notification-transactions-payment-method-apm-wait-notification.js";

/** Data associated with the response of an APM transaction. */
export type ApmResponse = {
  provider?: Provider13;
  /** URL to redirect the payer from the merchant's system to the payment method system. */
  redirectUrl?: string;
  /**
   * A string generated by the payment method to represent the session created on the payment method
   * platform to facilitate the creation of a transaction.
   */
  sessionToken?: string;
  /** Indicates the degree the merchant is funded for the transaction. */
  fundStatus?: FundStatusTransactionsPaymentMethodApmFundStatus;
  /**
   * Indicates to instruct the payer to wait for an update at the time the transaction is being
   * executed or that an update will be given later.
   */
  waitNotification?: WaitNotificationTransactionsPaymentMethodApmWaitNotification;
  /**
   * Indicates that a redirect to the payment method is not required. Some payment methods (for
   * example, SEPA Direct Debit) provide the option to redirect the customer to a page to display
   * additional information about the payment.
   */
  optionalRedirect?: OptionalRedirectTransactionsPaymentMethodApmOptionalRedirect;
  /** The reference the payment method provider created for the transaction. */
  providerTransactionReference?: string;
  /** The time the payment method provider created the transaction at on their system. */
  providerTimeCreated?: Date;
  /** A name of the payer from the payment method system. */
  providerPayerName?: string;
  bank?: BankAccount;
  mandate?: Mandate;
  /**
   * The recommended next action to be taken by the merchant based on the response given by the
   * payment method provider.
   */
  nextAction?: NextActionTransactionsPaymentMethodApmNextAction;
  /**
   * The recommended next action to be taken by the merchant based on the response given by the
   * payment method provider.
   */
  nextActionMessage?: string;
  /** Indicates the category of the alternate payment method . */
  category?: CategoryTransactionsPaymentMethodApmCategory;
  /** The time in seconds that the QR Code or redirect url is valid for. */
  secondsToExpire?: number;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const apmResponseProperties: s.Shape<ApmResponse> = {
  provider: s.optional(s.lazy(() => provider13InternalSchema)),
  redirectUrl: s.optional(s.string()),
  sessionToken: s.optional(s.string()),
  fundStatus: s.optional(s.lazy(() => fundStatusTransactionsPaymentMethodApmFundStatusSchema)),
  waitNotification: s.optional(
    s.lazy(() => waitNotificationTransactionsPaymentMethodApmWaitNotificationSchema),
  ),
  optionalRedirect: s.optional(
    s.lazy(() => optionalRedirectTransactionsPaymentMethodApmOptionalRedirectSchema),
  ),
  providerTransactionReference: s.optional(s.string()),
  providerTimeCreated: s.optional(s.dateTime()),
  providerPayerName: s.optional(s.string()),
  bank: s.optional(s.lazy(() => bankAccountSchema)),
  mandate: s.optional(s.lazy(() => mandateSchema)),
  nextAction: s.optional(s.lazy(() => nextActionTransactionsPaymentMethodApmNextActionSchema)),
  nextActionMessage: s.optional(s.string()),
  category: s.optional(s.lazy(() => categoryTransactionsPaymentMethodApmCategorySchema)),
  secondsToExpire: s.optional(s.float64()),
  _keysMap: {
    redirectUrl: "redirect_url",
    sessionToken: "session_token",
    fundStatus: "fund_status",
    waitNotification: "wait_notification",
    optionalRedirect: "optional_redirect",
    providerTransactionReference: "provider_transaction_reference",
    providerTimeCreated: "provider_time_created",
    providerPayerName: "provider_payer_name",
    nextAction: "next_action",
    nextActionMessage: "next_action_message",
    secondsToExpire: "seconds_to_expire",
  },
};

export const apmResponseInternalSchema: Schema<ApmResponse> = s.object<ApmResponse>(apmResponseProperties, {
  additionalProperties: s.json(),
});

export const apmResponseSchema: Schema<ApmResponse> = s.lazySchema(() =>
  s.object<ApmResponse>(
    {
      ...apmResponseProperties,
      provider: s.optional(s.lazy(() => provider13Schema)),
      sessionToken: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      providerTransactionReference: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      providerPayerName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      nextActionMessage: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
    },
    { additionalProperties: s.json() },
  ),
);
