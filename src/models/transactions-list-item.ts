import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  currencyBatchesTransactionsCurrencySchema,
  type CurrencyBatchesTransactionsCurrency,
} from "./currency-batches-transactions-currency.js";
import { order38InternalSchema, order38Schema, type Order38 } from "./order38.js";
import {
  paymentMethodListResponseInternalSchema,
  paymentMethodListResponseSchema,
  type PaymentMethodListResponse,
} from "./payment-method-list-response.js";
import {
  statusSettlementTransactionsStatusSchema,
  type StatusSettlementTransactionsStatus,
} from "./status-settlement-transactions-status.js";
import {
  systemSettlementReportingInternalSchema,
  systemSettlementReportingSchema,
  type SystemSettlementReporting,
} from "./system-settlement-reporting.js";
import {
  taxInMerchantAmountSettlementTransactionsTaxInMerchantAmountSchema,
  type TaxInMerchantAmountSettlementTransactionsTaxInMerchantAmount,
} from "./tax-in-merchant-amount-settlement-transactions-tax-in-merchant-amount.js";
import {
  transactionFeesInternalSchema,
  transactionFeesSchema,
  type TransactionFees,
} from "./transaction-fees.js";
import {
  TypeSettlementTransactionsType,
  typeSettlementTransactionsTypeSchema,
} from "./type-settlement-transactions-type.js";

export type TransactionsListItem = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future. This field is currently empty and is present for forward compatibility.
   */
  id?: string;
  /**
   * A unique identifier that identifies the transaction when it is funded or being funded.It is
   * only created if Global Payments funds the transaction and is different to the transaction id.
   */
  settlementTransactionReference?: string;
  /**
   * The time indicating when the transaction was created. This represents the day of the
   * transaction and will not identically match the real time transaction time created value
   */
  timeCreated?: string;
  /**
   * Indicates where a transaction is in its lifecycle.
   *    * `FUNDED` - A Transaction where the funds have transferred between payer and merchant as
   *      expected.
   */
  status?: StatusSettlementTransactionsStatus;
  /**
   * Describes whether the transaction is a SALE, that moves funds from Payer to Merchant, or a
   * REFUND where funds move from Merchant to Payer.
   *                  * `SALE` - indicates the movement, or the attempt to move, funds from payer to
   *                    a merchant.
   *                  * `REFUND` - indicates the movement, or the attempt to move, funds from
   *                    merchant to the payer.
   *
   * @default TypeSettlementTransactionsType.Sale
   */
  type?: TypeSettlementTransactionsType;
  /**
   * The amount to transfer between Payer and Merchant for a SALE or a REFUND. It is always
   * represented in the lowest denomination of the related currency. and with no decimal point.
   */
  amount?: string;
  /** The currency of the amount in ISO-4217(alpha-3). */
  currency?: CurrencyBatchesTransactionsCurrency;
  /**
   * The amount of cash requested at the point of sale that the card holder recieves. This amount
   * can be charged independently or it is addded to the cost of the items purchased.
   */
  cashbackAmount?: string;
  /** The amount of the transaction in the merchant's currency that is funded to the merchant. */
  merchantAmount?: string;
  /** The currency of the amount in ISO-4217(alpha-3). */
  merchantCurrency?: CurrencyBatchesTransactionsCurrency;
  /** The discount amount of the transaction in the currency the transaction was captured in. */
  discountAmount?: string;
  /** The discount amount of the transaction in the currency the merchant gets funded in. */
  merchantDiscountAmount?: string;
  /**
   * Indicates if a tax amount was included in the setttled merchant amount
   *     * `TRUE` - The tax amount was added to the settled merchant amount
   *     * `FALSE` - The tax amount was not added to the settled merchant amount
   */
  taxInMerchantAmount?: TaxInMerchantAmountSettlementTransactionsTaxInMerchantAmount;
  /** The total amount of tax charges associated with this transaction. */
  taxAmount?: string;
  /**
   * The total amount of tax charges associated with this transaction in the currency the Merchant
   * gets taxed in
   */
  merchantTaxAmount?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  /**
   * Merchant's time indicating when the transaction was first created. Value is in ISO-8601 format.
   */
  timeCreatedReference?: string;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future. This field is currently empty and is present for forward compatibility.
   */
  depositId?: string;
  /**
   * The time indicating when the transaction was created. This represents the day of the
   * transaction and will not identically match the real time transaction time created value
   */
  depositTimeCreated?: string;
  /**
   * Indicates where a transaction is in its lifecycle.
   *    * `FUNDED` - A Transaction where the funds have transferred between payer and merchant as
   *      expected.
   */
  depositStatus?: StatusSettlementTransactionsStatus;
  /**
   * The amount that should be credited or debited to a bank account, for a deposit. It is always
   * represented in the lowest denomination of the related currency.
   */
  depositAmount?: string;
  /** A Global Payments created reference that uniquely identifies the batch. */
  batchId?: string;
  /**
   * The time indicating when the transaction was created. This represents the day of the
   * transaction and will not identically match the real time transaction time created value
   */
  batchTimeCreated?: string;
  order?: Order38;
  paymentMethod?: PaymentMethodListResponse;
  /** A breakdown of the fees associated with the transaction. */
  fees?: TransactionFees;
  /**
   * Acquiring data used to identify a merchant when other systems are used by the merchant to
   * payment process.
   */
  system?: SystemSettlementReporting;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const transactionsListItemProperties: s.Shape<TransactionsListItem> = {
  id: s.optional(s.string()),
  settlementTransactionReference: s.optional(s.string()),
  timeCreated: s.optional(s.string()),
  status: s.optional(s.lazy(() => statusSettlementTransactionsStatusSchema)),
  type: s.defaulted(typeSettlementTransactionsTypeSchema, TypeSettlementTransactionsType.Sale),
  amount: s.optional(s.string()),
  currency: s.optional(s.lazy(() => currencyBatchesTransactionsCurrencySchema)),
  cashbackAmount: s.optional(s.string()),
  merchantAmount: s.optional(s.string()),
  merchantCurrency: s.optional(s.lazy(() => currencyBatchesTransactionsCurrencySchema)),
  discountAmount: s.optional(s.string()),
  merchantDiscountAmount: s.optional(s.string()),
  taxInMerchantAmount: s.optional(
    s.lazy(() => taxInMerchantAmountSettlementTransactionsTaxInMerchantAmountSchema),
  ),
  taxAmount: s.optional(s.string()),
  merchantTaxAmount: s.optional(s.string()),
  reference: s.optional(s.string()),
  timeCreatedReference: s.optional(s.string()),
  depositId: s.optional(s.string()),
  depositTimeCreated: s.optional(s.string()),
  depositStatus: s.optional(s.lazy(() => statusSettlementTransactionsStatusSchema)),
  depositAmount: s.optional(s.string()),
  batchId: s.optional(s.string()),
  batchTimeCreated: s.optional(s.string()),
  order: s.optional(s.lazy(() => order38InternalSchema)),
  paymentMethod: s.optional(s.lazy(() => paymentMethodListResponseInternalSchema)),
  fees: s.optional(s.lazy(() => transactionFeesInternalSchema)),
  system: s.optional(s.lazy(() => systemSettlementReportingInternalSchema)),
  _keysMap: {
    settlementTransactionReference: "settlement_transaction_reference",
    timeCreated: "time_created",
    cashbackAmount: "cashback_amount",
    merchantAmount: "merchant_amount",
    merchantCurrency: "merchant_currency",
    discountAmount: "discount_amount",
    merchantDiscountAmount: "merchant_discount_amount",
    taxInMerchantAmount: "tax_in_merchant_amount",
    taxAmount: "tax_amount",
    merchantTaxAmount: "merchant_tax_amount",
    timeCreatedReference: "time_created_reference",
    depositId: "deposit_id",
    depositTimeCreated: "deposit_time_created",
    depositStatus: "deposit_status",
    depositAmount: "deposit_amount",
    batchId: "batch_id",
    batchTimeCreated: "batch_time_created",
    paymentMethod: "payment_method",
  },
};

export const transactionsListItemInternalSchema: Schema<TransactionsListItem> =
  s.object<TransactionsListItem>(transactionsListItemProperties, { additionalProperties: s.json() });

export const transactionsListItemSchema: Schema<TransactionsListItem> = s.lazySchema(() =>
  s.object<TransactionsListItem>(
    {
      ...transactionsListItemProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      amount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      cashbackAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      discountAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantDiscountAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      taxAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
      depositId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      batchId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      order: s.optional(s.lazy(() => order38Schema)),
      paymentMethod: s.optional(s.lazy(() => paymentMethodListResponseSchema)),
      fees: s.optional(s.lazy(() => transactionFeesSchema)),
      system: s.optional(s.lazy(() => systemSettlementReportingSchema)),
    },
    { additionalProperties: s.json() },
  ),
);
