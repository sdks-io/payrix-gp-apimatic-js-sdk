import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { action74Schema, type Action74 } from "./action74.js";
import {
  channelVerificationsChannelSchema,
  type ChannelVerificationsChannel,
} from "./channel-verifications-channel.js";
import {
  currencyBatchesTransactionsCurrencySchema,
  type CurrencyBatchesTransactionsCurrency,
} from "./currency-batches-transactions-currency.js";
import {
  paymentMethod52InternalSchema,
  paymentMethod52Schema,
  type PaymentMethod52,
} from "./payment-method52.js";
import {
  statusVerificationsStatusSchema,
  type StatusVerificationsStatus,
} from "./status-verifications-status.js";

export type CreateResponseVerifications = {
  /** A unique identifier generated by Global Payments to identify a verification */
  id?: string;
  /** Time indicating when the object was created in ISO-8601 format. */
  timeCreated?: Date;
  /** Indicates where a resource object is in its life-cycle. */
  status?: StatusVerificationsStatus;
  /**
   * Describes whether the transaction was processed in a face to face(CP) scenario or a Customer
   * Not Present (CNP) scenario.
   * * `CP` - A Customer Present transaction is when the payer and the merchant are in direct face
   *   to face contact when exchanging payment method information to fulfill a transaction. e.g. in
   *   a store and paying at the counter that is attended by a clerk
   * * `CNP` - A Customer NOT Present transaction is when the payer and the merchant are not
   *   together when exchanging payment method information to fulfill a transaction. e.g. a
   *   transaction executed from a merchant's website or over the phone
   */
  channel?: ChannelVerificationsChannel;
  /** The currency of the amount in ISO-4217(alpha-3). */
  currency?: CurrencyBatchesTransactionsCurrency;
  /** The country in ISO-3166-1(alpha-2 code) format. */
  country?: string;
  /** A unique identifier for the merchant set by Global Payments. */
  merchantId?: string;
  /** A meaningful label for the merchant set by Global Payments. */
  merchantName?: string;
  /** A unique identifier for the merchant account set by Global Payments. */
  accountId?: string;
  /** A meaningful label for the merchant account set by Global Payments. */
  accountName?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  paymentMethod?: PaymentMethod52;
  /** A Global Payments created reference that uniquely identifies the batch. */
  batchId?: string;
  action?: Action74;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const createResponseVerificationsProperties: s.Shape<CreateResponseVerifications> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  status: s.optional(s.lazy(() => statusVerificationsStatusSchema)),
  channel: s.optional(s.lazy(() => channelVerificationsChannelSchema)),
  currency: s.optional(s.lazy(() => currencyBatchesTransactionsCurrencySchema)),
  country: s.optional(s.string()),
  merchantId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  reference: s.optional(s.string()),
  paymentMethod: s.optional(s.lazy(() => paymentMethod52InternalSchema)),
  batchId: s.optional(s.string()),
  action: s.optional(s.lazy(() => action74Schema)),
  _keysMap: {
    timeCreated: "time_created",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account_id",
    accountName: "account_name",
    paymentMethod: "payment_method",
    batchId: "batch_id",
  },
};

export const createResponseVerificationsInternalSchema: Schema<CreateResponseVerifications> =
  s.object<CreateResponseVerifications>(createResponseVerificationsProperties, {
    additionalProperties: s.json(),
  });

export const createResponseVerificationsSchema: Schema<CreateResponseVerifications> = s.lazySchema(() =>
  s.object<CreateResponseVerifications>(
    {
      ...createResponseVerificationsProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
      paymentMethod: s.optional(s.lazy(() => paymentMethod52Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
