import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { deviceInternalSchema, deviceSchema, type Device } from "./device.js";
import { order7InternalSchema, order7Schema, type Order7 } from "./order7.js";
import {
  paymentMethod13InternalSchema,
  paymentMethod13Schema,
  type PaymentMethod13,
} from "./payment-method13.js";
import { statusConsentsStatusSchema, type StatusConsentsStatus } from "./status-consents-status.js";

export type Consent = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future.
   */
  id?: string;
  /** Merchant defined field to reference this consent request. */
  reference?: string;
  /** Status of the consent */
  status?: StatusConsentsStatus;
  /** A further description of the status of a consent. */
  statusDescription?: string;
  /**
   * The merchant's DBA (Doing Business As) name or the alternate name the merchant may be known as.
   */
  dba?: string;
  device?: Device;
  order?: Order7;
  paymentMethod?: PaymentMethod13;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const consentProperties: s.Shape<Consent> = {
  id: s.optional(s.string()),
  reference: s.optional(s.string()),
  status: s.optional(s.lazy(() => statusConsentsStatusSchema)),
  statusDescription: s.optional(s.string()),
  dba: s.optional(s.string()),
  device: s.optional(s.lazy(() => deviceInternalSchema)),
  order: s.optional(s.lazy(() => order7InternalSchema)),
  paymentMethod: s.optional(s.lazy(() => paymentMethod13InternalSchema)),
  _keysMap: {
    statusDescription: "status_description",
    paymentMethod: "payment_method",
  },
};

export const consentInternalSchema: Schema<Consent> = s.object<Consent>(consentProperties, {
  additionalProperties: s.json(),
});

export const consentSchema: Schema<Consent> = s.lazySchema(() =>
  s.object<Consent>(
    {
      ...consentProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
      dba: s.optional(s.string().check(s.minLength(1), s.maxLength(255))),
      device: s.optional(s.lazy(() => deviceSchema)),
      order: s.optional(s.lazy(() => order7Schema)),
      paymentMethod: s.optional(s.lazy(() => paymentMethod13Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
