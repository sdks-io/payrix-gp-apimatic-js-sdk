import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { action11InternalSchema, action11Schema, type Action11 } from "./action11.js";
import {
  channelAuthenticationsChannelSchema,
  type ChannelAuthenticationsChannel,
} from "./channel-authentications-channel.js";
import {
  countryAuthenticationsCountrySchema,
  type CountryAuthenticationsCountry,
} from "./country-authentications-country.js";
import {
  currencyAuthenticationsCurrencySchema,
  type CurrencyAuthenticationsCurrency,
} from "./currency-authentications-currency.js";
import {
  paymentMethod9InternalSchema,
  paymentMethod9Schema,
  type PaymentMethod9,
} from "./payment-method9.js";
import {
  sourceAuthenticationsSourceSchema,
  type SourceAuthenticationsSource,
} from "./source-authentications-source.js";
import {
  statusAuthenticationsStatusSchema,
  type StatusAuthenticationsStatus,
} from "./status-authentications-status.js";
import { systemInternalSchema, systemSchema, type System } from "./system.js";

export type SingleResponse = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the authentication and must be used to action or
   * reference that authentication.
   */
  id?: string;
  /** Time indicating when the object was created in ISO-8601 format. */
  timeCreated?: Date;
  /**
   * Indicates where the authentication is in its lifecycle
   * * `AVAILABLE` - An authentication mechanism is available. The next step is to initiate the
   *   authentication. No liability shift at this stage.
   * * `NOT_AVAILABLE` - The authentication mechanism is not available. The next step is to check
   *   for availability of another authentication mechanism. No liability shift at this stage.
   * * `NOT_ENROLLED` - The payer's payment method is not enrolled in 3DS version 1 or version 2. If
   *   the card is a Visa or Mastercard a liability shift is achieved and the recommendation is
   *   execute the care authorization. However there us no liability shift at this stage for Amex,so
   *   the recommendation is not for go for card authorization.
   * * `CHALLENGE_REQUIRED` - The authentication mechanism is available and the next step is to
   *   facilitate authentication of the payer. No liability shift at this stage.
   * * `SUCCESS_AUTHENTICATED` - The authentication of the payer has been a success and a liability
   *   shift has been achieved so the recommendation is to go for authorization
   * * `SUCCESS_ATTEMPT_MADE` - A valid attempt to authenticate the payer has been executed and a
   *   liability shift has been achieved so the recommendation is to go for authorization.
   * * `NOT_AUTHENTICATED` - The payer did not authenticate therefore a liability shift has not been
   *   achieved. The recommendation is to not proceed with card authorization.
   * * `FAILED` - A step in the authentication process has errored and there do not go for card
   *   authorization.
   * * `CHALLENGE_PREFERENCE_ACKNOWLEDGED_INFORMATIONAL_ONLY`
   */
  status?: StatusAuthenticationsStatus;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific merchant. Begins with the three letters,
   * MER.
   */
  merchantId?: string;
  /** A meaningful label that better identifies the merchant. */
  merchantName?: string;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific account. Begins with the three letters,
   * TRA.
   */
  accountId?: string;
  /** A meaningful label that better identifies the account. */
  accountName?: string;
  /**
   * Describes whether the transaction was processed in a face to face(CP) scenario or a Customer
   * Not Present (CNP) scenario.
   * * `CP` - A Customer Present transaction is when the payer and the merchant are in direct face
   *   to face contact when exchanging payment method information to fulfill a transaction. e.g. in
   *   a store and paying at the counter that is attended by a clerk.
   * * `CNP` - A Customer NOT Present transaction is when the payer and the merchant are not
   *   together when exchanging payment method information to fulfill a transaction. e.g. a
   *   transaction executed from a merchant's website or over the phone
   */
  channel?: ChannelAuthenticationsChannel;
  /**
   * The amount to transfer between Payer and Merchant for a SALE or a REFUND. It is always
   * represented in the lowest denomination of the related currency. and with no decimal point. Note
   * for European merchants: This field is mandatory for SCA.
   */
  amount?: string;
  /** The currency of the amount in ISO-4217(alpha-3). */
  currency?: CurrencyAuthenticationsCurrency;
  /**
   * This is the country the merchant is domiciled in. For example, if the merchant is based in
   * Canada it must be set to CA. if the merchant is based in England it must be set to GB. if the
   * merchant is based in USA it must be set to US. The country in ISO-3166-1(alpha-2 code) format.
   */
  country?: CountryAuthenticationsCountry;
  /**
   * Indicates the type of system used to initiate the authentication.
   * * `BROWSER`
   * * `MERCHANT_INITIATED`
   * * `MOBILE_SDK`
   */
  source?: SourceAuthenticationsSource;
  paymentMethod?: PaymentMethod9;
  /**
   * A unique identifier generated by Global Payments to identify the action returned on the
   * Authentication initiated
   */
  actionCreateId?: string;
  system?: System;
  action?: Action11;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const singleResponseProperties: s.Shape<SingleResponse> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  status: s.optional(s.lazy(() => statusAuthenticationsStatusSchema)),
  merchantId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  channel: s.optional(s.lazy(() => channelAuthenticationsChannelSchema)),
  amount: s.optional(s.string()),
  currency: s.optional(s.lazy(() => currencyAuthenticationsCurrencySchema)),
  country: s.optional(s.lazy(() => countryAuthenticationsCountrySchema)),
  source: s.optional(s.lazy(() => sourceAuthenticationsSourceSchema)),
  paymentMethod: s.optional(s.lazy(() => paymentMethod9InternalSchema)),
  actionCreateId: s.optional(s.string()),
  system: s.optional(s.lazy(() => systemInternalSchema)),
  action: s.optional(s.lazy(() => action11InternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account_id",
    accountName: "account_name",
    paymentMethod: "payment_method",
    actionCreateId: "action_create_id",
  },
};

export const singleResponseInternalSchema: Schema<SingleResponse> = s.object<SingleResponse>(
  singleResponseProperties,
  { additionalProperties: s.json() },
);

export const singleResponseSchema: Schema<SingleResponse> = s.lazySchema(() =>
  s.object<SingleResponse>(
    {
      ...singleResponseProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      merchantName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      accountName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      amount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      paymentMethod: s.optional(s.lazy(() => paymentMethod9Schema)),
      system: s.optional(s.lazy(() => systemSchema)),
      action: s.optional(s.lazy(() => action11Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
