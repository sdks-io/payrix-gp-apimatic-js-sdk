import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import { action28InternalSchema, action28Schema, type Action28 } from "./action28.js";
import { responseFileSchema, type ResponseFile } from "./response-file.js";
import {
  statusFileProcessingStatusSchema,
  type StatusFileProcessingStatus,
} from "./status-file-processing-status.js";

/**
 * Response returned by `GET /files/{id}` containing the full details of a File Processing resource.
 * When the file has finished processing, `response_files` will contain the signed URL(s) to
 * download the encrypted response file(s).
 */
export type FileDetailsResponse2 = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments which can be used to check the details of the file.
   */
  id?: string;
  /** Global Payments generated time indicating when the object was created in ISO-8601 format. */
  timeCreated?: Date;
  /**
   * The overall status of the file being processed. *`INITIATED` - The initial status of all newly
   * created file resources. Occurs after the API sends the signed URL to upload your file to.
   * *`UPLOADED` - Occurs after you upload the bulk file to the signed URL provided by the API.
   * *`PENDING` - Occurs after record validation and the combinations are deemed valid by our File
   * Processing solution. *`SUBMITTED` - Occurs once the file has been fully processed. *`FAILED`
   * -Occurs after record validation if the combinations are deemed invalid by our File Processing
   * solution *`COMPLETED` - Occurs after the response file is generated and the API sends you the
   * signed URL to download the encrypted response file via webhook notification.
   */
  status?: StatusFileProcessingStatus;
  /** A unique identifier for the merchant set by Global Payments. */
  merchantId?: string;
  /** A meaningful label that better identifies the merchant. */
  merchantName?: string;
  /** A unique identifier for the merchant account set by Global Payments. */
  accountId?: string;
  /** A meaningful label that better identifies the account. */
  accountName?: string;
  /**
   * The total number of records contained in the uploaded bulk file. Returned as an empty string
   * until the file has been validated and processed.
   */
  totalRecordCount?: string;
  /**
   * A list of the encrypted response files generated by the File Processing solution. Empty until
   * the file's `status` is `COMPLETED`.
   */
  responseFiles?: ResponseFile[];
  /** Information about the specific action performed on the platform for this resource. */
  action?: Action28;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const fileDetailsResponse2Properties: s.Shape<FileDetailsResponse2> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  status: s.optional(s.lazy(() => statusFileProcessingStatusSchema)),
  merchantId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountId: s.optional(s.string()),
  accountName: s.optional(s.string()),
  totalRecordCount: s.optional(s.string()),
  responseFiles: s.optional(s.array(s.lazy(() => responseFileSchema))),
  action: s.optional(s.lazy(() => action28InternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    merchantId: "merchant_id",
    merchantName: "merchant_name",
    accountId: "account_id",
    accountName: "account_name",
    totalRecordCount: "total_record_count",
    responseFiles: "response_files",
  },
};

export const fileDetailsResponse2InternalSchema: Schema<FileDetailsResponse2> =
  s.object<FileDetailsResponse2>(fileDetailsResponse2Properties, { additionalProperties: s.json() });

export const fileDetailsResponse2Schema: Schema<FileDetailsResponse2> = s.lazySchema(() =>
  s.object<FileDetailsResponse2>(
    {
      ...fileDetailsResponse2Properties,
      action: s.optional(s.lazy(() => action28Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
