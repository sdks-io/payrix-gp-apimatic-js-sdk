import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  notifications19InternalSchema,
  notifications19Schema,
  type Notifications19,
} from "./notifications19.js";
import { shippableLinksShippableSchema, type ShippableLinksShippable } from "./shippable-links-shippable.js";
import { statusLinksStatusSchema, type StatusLinksStatus } from "./status-links-status.js";
import { transaction15InternalSchema, transaction15Schema, type Transaction15 } from "./transaction15.js";
import { typeLinksTypeSchema, type TypeLinksType } from "./type-links-type.js";
import {
  usageModeLinksUsageModeSchema,
  type UsageModeLinksUsageMode,
} from "./usage-mode-links-usage-mode.js";

export type Link3 = {
  /** A unique identifier generated by Global Payments to identify the link. */
  id?: string;
  /** The URL that the customer should be redirected to in order to make their payment. */
  url?: string;
  /**
   * The overall status of the instance of the resource.The overall status of the instance of the
   * resource. *`ACTIVE` - When a link is initially created it is in an ACTIVE status waiting to be
   * paid. Links can only be paid when they are in a ACTIVE status. *`CLOSED` - When a multi use
   * link is paid it max number of time it is updated to be CLOSED automatically. A CLOSED link
   * cannot be paid again. *`PAID` - When a single use link is paid once then its status is updated
   * to PAID automatically. A PAID link cannot be paid again. *`INACTIVE` - An INACTIVE link is a
   * link that you have marked as INACTIVE. Links can be manually updated / toggled between ACTIVE
   * and INACTIVE using the PATCH request. A link cannot be paid while it is in an INACTIVE state.
   * *`EXPIRED` - An EXPIRED link is a link the expiration_date set in the request is in the past.
   */
  status?: StatusLinksStatus;
  /** GP API specific label that indicates the type resource an instance is. */
  type?: TypeLinksType;
  /** Indicates whether the link can be used once or multiple times */
  usageMode?: UsageModeLinksUsageMode;
  /** The number of the times that the link can be used or paid. */
  usageLimit?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  /** A descriptive name for the link. This will be visible to the customer on the payment page. */
  name?: string;
  /**
   * A detailed description of your link that will be visible to the customer on the payment page.
   */
  description?: string;
  /**
   * Indicates if you want to capture the customers shipping information on the hosted payment page.
   * If you enable this field you can also set an optional shipping fee in the shipping_amount.
   */
  shippable?: ShippableLinksShippable;
  /** Indicates the cost of shipping when the shippable field is set to YES. */
  shippingAmount?: string;
  /** Indicates the number of times that a link has already been successfully paid. */
  usageCount?: string;
  /** The number of times a link has been viewed. */
  viewedCount?: number;
  /**
   * Indicates the date and time after which the link can no longer be used or paid. Please note
   * that the timezone is in UTC+0
   */
  expirationDate?: string;
  /**
   * Base64 encoded images of the products / services that you want to display on the hosted payment
   * page.
   */
  images?: string[];
  notifications?: Notifications19;
  transactions?: Transaction15[];
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const link3Properties: s.Shape<Link3> = {
  id: s.optional(s.string()),
  url: s.optional(s.string()),
  status: s.optional(s.lazy(() => statusLinksStatusSchema)),
  type: s.optional(s.lazy(() => typeLinksTypeSchema)),
  usageMode: s.optional(s.lazy(() => usageModeLinksUsageModeSchema)),
  usageLimit: s.optional(s.string()),
  reference: s.optional(s.string()),
  name: s.optional(s.string()),
  description: s.optional(s.string()),
  shippable: s.optional(s.lazy(() => shippableLinksShippableSchema)),
  shippingAmount: s.optional(s.string()),
  usageCount: s.optional(s.string()),
  viewedCount: s.optional(s.float64()),
  expirationDate: s.optional(s.string()),
  images: s.optional(s.array(s.string())),
  notifications: s.optional(s.lazy(() => notifications19InternalSchema)),
  transactions: s.optional(s.array(s.lazy(() => transaction15InternalSchema))),
  _keysMap: {
    usageMode: "usage_mode",
    usageLimit: "usage_limit",
    shippingAmount: "shipping_amount",
    usageCount: "usage_count",
    viewedCount: "viewed_count",
    expirationDate: "expiration_date",
  },
};

export const link3InternalSchema: Schema<Link3> = s.object<Link3>(link3Properties, {
  additionalProperties: s.json(),
});

export const link3Schema: Schema<Link3> = s.lazySchema(() =>
  s.object<Link3>(
    {
      ...link3Properties,
      reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
      name: s.optional(s.string().check(s.minLength(1), s.maxLength(120))),
      description: s.optional(s.string().check(s.minLength(1), s.maxLength(250))),
      notifications: s.optional(s.lazy(() => notifications19Schema)),
      transactions: s.optional(s.array(s.lazy(() => transaction15Schema))),
    },
    { additionalProperties: s.json() },
  ),
);
