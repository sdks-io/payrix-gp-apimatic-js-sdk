import { action67InternalSchema, action67Schema, type Action67 } from "./action67.js";
import {
  currencyAuthenticationsCurrencySchema,
  type CurrencyAuthenticationsCurrency,
} from "./currency-authentications-currency.js";
import {
  paymentMethod50InternalSchema,
  paymentMethod50Schema,
  type PaymentMethod50,
} from "./payment-method50.js";
import {
  statusTransactionsStatusSchema,
  type StatusTransactionsStatus,
} from "./status-transactions-status.js";
import {
  TransactionTypeAuthenticationsTransactionType,
  transactionTypeAuthenticationsTransactionTypeSchema,
} from "./transaction-type-authentications-transaction-type.js";
import { transfer1InternalSchema, transfer1Schema, type Transfer1 } from "./transfer1.js";

export type SplitAmountResponseTransactions = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future.
   */
  id?: string;
  /** Time indicating when the transaction was created in ISO-8601 format. */
  timeCreated?: Date;
  /**
   * Indicates where a transaction is in its lifecycle.
   * * `FOR_REVIEW `- A Transaction is being created with key information like amount and goods and
   *   services being purchased.It must be reviewed and subsequently actioned before going for
   *   authorization. This status is used if the transaction needs to be shown to the payer before
   *   proceeding to authorization.
   * * `INITIATED` - A Transaction has been successfully initiated. An update on its status is
   *   expected via a separate asynchronous notification to a webhook.
   * * `PENDING` - A Transaction has been sent to the payment method provider and are waiting for a
   *   result.
   * * `PREAUTHORIZED` - A Transaction has been approved but a capture request is required to
   *   commence the movement of funds.
   * * `CAPTURED` - A Transaction has been successfully authorized and captured. The funding process
   *   will commence once the transaction remains in this status.
   * * `REVERSED` - A Transaction that had a status of PENDING, PREAUTHORIZED or CAPTURED has
   *   subsequently been reversed which voids/cancels a transaction before it is funded.
   * * `DECLINED` - A Transaction where the payment method provider declined the transfer of funds
   *   between the payer and the merchant.
   * * `FUNDED` - A Transaction where the funds have transferred between payer and merchant as
   *   expected.
   * * `FAILED` - A Transaction that experienced an error after it was already created. For example
   *   a transaction that timed out waiting for a response or a transaction was successfully
   *   initiated and sent to a terminal/device that subsequently experienced an issue.
   * * `REJECTED` - A Transaction where the funds were expected to transfer between payer and
   *   merchant but the transfer was rejected during the funding process. This rarely happens but
   *   when it does it is usually addressed by Global Payments operations.
   */
  status?: StatusTransactionsStatus;
  /**
   * This is the country the merchant is domiciled in. For example, if the merchant is based in
   * Canada it must be set to CA.if the merchant is based in England it must be set to GB.if the
   * merchant is based in USA it must be set to US.The country in ISO-3166-1(alpha-2 code) format.
   */
  country?: string;
  /** The currency of the amount in ISO-4217(alpha-3). */
  currency?: CurrencyAuthenticationsCurrency;
  /**
   * Describes whether the transaction is a SALE, that moves funds from Payer to Merchant, or a
   * REFUND where funds move from Merchant to Payer.
   * * `SALE` - indicates the movement, or the attempt to move, funds from payer to a merchant.
   * * `REFUND` - indicates the movement, or the attempt to move, funds from merchant to the payer.
   *
   * @default TransactionTypeAuthenticationsTransactionType.Sale
   */
  type?: TransactionTypeAuthenticationsTransactionType;
  /**
   * The amount to transfer between Payer and Merchant for a SALE or a REFUND. It is always
   * represented in the lowest denomination of the related currency. and with no decimal point.
   */
  amount?: string;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific merchant. Begins with the three letters,
   * MER.
   */
  merchantId?: string;
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. This
   * id is used when actioning or referencing a specific account. Begins with the three letters,
   * TRA.
   */
  accountId?: string;
  /** A meaningful label that better identifies the merchant. */
  merchantName?: string;
  /** A meaningful label that better identifies the account. */
  accountName?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  paymentMethod?: PaymentMethod50;
  transfers?: Transfer1[];
  action?: Action67;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const splitAmountResponseTransactionsProperties: s.Shape<SplitAmountResponseTransactions> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  status: s.optional(s.lazy(() => statusTransactionsStatusSchema)),
  country: s.optional(s.string()),
  currency: s.optional(s.lazy(() => currencyAuthenticationsCurrencySchema)),
  type: s.defaulted(
    transactionTypeAuthenticationsTransactionTypeSchema,
    TransactionTypeAuthenticationsTransactionType.Sale,
  ),
  amount: s.optional(s.string()),
  merchantId: s.optional(s.string()),
  accountId: s.optional(s.string()),
  merchantName: s.optional(s.string()),
  accountName: s.optional(s.string()),
  reference: s.optional(s.string()),
  paymentMethod: s.optional(s.lazy(() => paymentMethod50InternalSchema)),
  transfers: s.optional(s.array(s.lazy(() => transfer1InternalSchema))),
  action: s.optional(s.lazy(() => action67InternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    merchantId: "merchant_id",
    accountId: "account_id",
    merchantName: "merchant_name",
    accountName: "account_name",
    paymentMethod: "payment_method",
  },
};

export const splitAmountResponseTransactionsInternalSchema: Schema<SplitAmountResponseTransactions> =
  s.object<SplitAmountResponseTransactions>(splitAmountResponseTransactionsProperties, {
    additionalProperties: s.json(),
  });

export const splitAmountResponseTransactionsSchema: Schema<SplitAmountResponseTransactions> = s.lazySchema(
  () =>
    s.object<SplitAmountResponseTransactions>(
      {
        ...splitAmountResponseTransactionsProperties,
        id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        country: s.optional(s.string().check(s.minLength(2), s.maxLength(2))),
        amount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        merchantId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        accountId: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        merchantName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        accountName: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
        reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
        paymentMethod: s.optional(s.lazy(() => paymentMethod50Schema)),
        transfers: s.optional(s.array(s.lazy(() => transfer1Schema))),
        action: s.optional(s.lazy(() => action67Schema)),
      },
      { additionalProperties: s.json() },
    ),
);
