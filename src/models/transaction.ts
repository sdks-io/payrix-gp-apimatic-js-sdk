import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  currencyBatchesTransactionsCurrencySchema,
  type CurrencyBatchesTransactionsCurrency,
} from "./currency-batches-transactions-currency.js";
import {
  paymentMethod10InternalSchema,
  paymentMethod10Schema,
  type PaymentMethod10,
} from "./payment-method10.js";
import {
  statusBatchesTransactionsStatusSchema,
  type StatusBatchesTransactionsStatus,
} from "./status-batches-transactions-status.js";
import {
  TransactionTypeAuthenticationsTransactionType,
  transactionTypeAuthenticationsTransactionTypeSchema,
} from "./transaction-type-authentications-transaction-type.js";

export type Transaction = {
  /**
   * A unique identifier that is used to identify and reference an instance of this resource. It is
   * generated by Global Payments to identify the transaction and must be used to action that
   * transaction in future.
   */
  id?: string;
  /** Time indicating when the transaction was created in ISO-8601 format. */
  timeCreated?: Date;
  /**
   * Indicates where a transaction is in its lifecycle.
   * * `BATCHED `- A Transaction has been successfully Batched
   * * `CAPTURED` - A Transaction has been successfully authorized and captured. The funding process
   *   will commence once the transaction remains in this status.
   */
  status?: StatusBatchesTransactionsStatus;
  /**
   * Describes whether the transaction is a SALE, that moves funds from Payer to Merchant, or a
   * REFUND where funds move from Merchant to Payer.
   * * `SALE` - indicates the movement, or the attempt to move, funds from payer to a merchant.
   * * `REFUND` - indicates the movement, or the attempt to move, funds from merchant to the payer.
   *
   * @default TransactionTypeAuthenticationsTransactionType.Sale
   */
  type?: TransactionTypeAuthenticationsTransactionType;
  /**
   * The amount to transfer between Payer and Merchant for a SALE or a REFUND. It is always
   * represented in the lowest denomination of the related currency. and with no decimal point.
   */
  amount?: string;
  /** The total amount of tax charges associated with this transaction. */
  taxAmount?: string;
  /** The currency of the amount in ISO-4217(alpha-3). */
  currency?: CurrencyBatchesTransactionsCurrency;
  /** The amount of the gratuity for a transaction. */
  gratuityAmount?: string;
  /**
   * The amount that reflects the additional charge the merchant applied to the transaction for
   * using a specific payment method.
   */
  surchargeAmount?: string;
  /** The amount of the transaction that relates to cashback. */
  cashbackAmount?: string;
  /** Merchant defined field to reference the transaction. */
  reference?: string;
  paymentMethod?: PaymentMethod10;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const transactionProperties: s.Shape<Transaction> = {
  id: s.optional(s.string()),
  timeCreated: s.optional(s.dateTime()),
  status: s.optional(s.lazy(() => statusBatchesTransactionsStatusSchema)),
  type: s.defaulted(
    transactionTypeAuthenticationsTransactionTypeSchema,
    TransactionTypeAuthenticationsTransactionType.Sale,
  ),
  amount: s.optional(s.string()),
  taxAmount: s.optional(s.string()),
  currency: s.optional(s.lazy(() => currencyBatchesTransactionsCurrencySchema)),
  gratuityAmount: s.optional(s.string()),
  surchargeAmount: s.optional(s.string()),
  cashbackAmount: s.optional(s.string()),
  reference: s.optional(s.string()),
  paymentMethod: s.optional(s.lazy(() => paymentMethod10InternalSchema)),
  _keysMap: {
    timeCreated: "time_created",
    taxAmount: "tax_amount",
    gratuityAmount: "gratuity_amount",
    surchargeAmount: "surcharge_amount",
    cashbackAmount: "cashback_amount",
    paymentMethod: "payment_method",
  },
};

export const transactionInternalSchema: Schema<Transaction> = s.object<Transaction>(transactionProperties, {
  additionalProperties: s.json(),
});

export const transactionSchema: Schema<Transaction> = s.lazySchema(() =>
  s.object<Transaction>(
    {
      ...transactionProperties,
      id: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      amount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      taxAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      gratuityAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      surchargeAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      cashbackAmount: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      reference: s.optional(s.string().check(s.minLength(8), s.maxLength(50))),
      paymentMethod: s.optional(s.lazy(() => paymentMethod10Schema)),
    },
    { additionalProperties: s.json() },
  ),
);
