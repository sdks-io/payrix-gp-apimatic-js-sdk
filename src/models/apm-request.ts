import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  brandTransactionsPaymentMethodApmBrandSchema,
  type BrandTransactionsPaymentMethodApmBrand,
} from "./brand-transactions-payment-method-apm-brand.js";
import {
  categoryTransactionsPaymentMethodApmCategorySchema,
  type CategoryTransactionsPaymentMethodApmCategory,
} from "./category-transactions-payment-method-apm-category.js";
import {
  paymentCodeInitiatorTransactionsPaymentMethodApmPaymentCodeInitiatorSchema,
  type PaymentCodeInitiatorTransactionsPaymentMethodApmPaymentCodeInitiator,
} from "./payment-code-initiator-transactions-payment-method-apm-payment-code-initiator.js";
import {
  providerTransactionsPaymentMethodApmProviderSchema,
  type ProviderTransactionsPaymentMethodApmProvider,
} from "./provider-transactions-payment-method-apm-provider.js";

export type ApmRequest = {
  /**
   * A string used to identify the payment method provider being used to execute this transaction.
   */
  provider?: ProviderTransactionsPaymentMethodApmProvider;
  /** Indicates the category of the alternate payment method . */
  category?: CategoryTransactionsPaymentMethodApmCategory;
  /** The countries that you want to allow payments from in ISO-3166-1(alpha-2 code) format. */
  countries?: string[];
  /** A string used to identify the payment method brand being used to execute this transaction. */
  brand?: BrandTransactionsPaymentMethodApmBrand;
  /**
   * Indicates who initiated the payment method code to execute the transaction.
   * * `PAYER` - The consumer who is paying the merchant.
   * * `MERCHANT` - The business who is providing goods or services to the payer.
   */
  paymentCodeInitiator?: PaymentCodeInitiatorTransactionsPaymentMethodApmPaymentCodeInitiator;
  /** The payment code generated by the initiator to execute the transaction. */
  paymentCode?: string;
  /** The time in seconds that the QR Code or redirect url is valid for. */
  secondsToExpire?: number;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const apmRequestProperties: s.Shape<ApmRequest> = {
  provider: s.optional(s.lazy(() => providerTransactionsPaymentMethodApmProviderSchema)),
  category: s.optional(s.lazy(() => categoryTransactionsPaymentMethodApmCategorySchema)),
  countries: s.optional(s.array(s.string())),
  brand: s.optional(s.lazy(() => brandTransactionsPaymentMethodApmBrandSchema)),
  paymentCodeInitiator: s.optional(
    s.lazy(() => paymentCodeInitiatorTransactionsPaymentMethodApmPaymentCodeInitiatorSchema),
  ),
  paymentCode: s.optional(s.string()),
  secondsToExpire: s.optional(s.float64()),
  _keysMap: {
    paymentCodeInitiator: "payment_code_initiator",
    paymentCode: "payment_code",
    secondsToExpire: "seconds_to_expire",
  },
};

export const apmRequestInternalSchema: Schema<ApmRequest> = s.object<ApmRequest>(apmRequestProperties, {
  additionalProperties: s.json(),
});

export const apmRequestSchema: Schema<ApmRequest> = s.lazySchema(() =>
  s.object<ApmRequest>(
    {
      ...apmRequestProperties,
      paymentCode: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
    },
    { additionalProperties: s.json() },
  ),
);
