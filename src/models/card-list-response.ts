import * as s from "../core/validation/index.js";
import type { JsonValue, Schema } from "../core/validation/schema.js";
import {
  brandAuthenticationsPaymentMethodCardBrandSchema,
  type BrandAuthenticationsPaymentMethodCardBrand,
} from "./brand-authentications-payment-method-card-brand.js";
import {
  fundingSettlementTransactionsPaymentMethodCardFundingSchema,
  type FundingSettlementTransactionsPaymentMethodCardFunding,
} from "./funding-settlement-transactions-payment-method-card-funding.js";

/** Data relating to the card payment method returned in a list response. */
export type CardListResponse = {
  /** Indicates the card brand that issued the card. */
  brand?: BrandAuthenticationsPaymentMethodCardBrand;
  /** Code generated by the card provider when the card is successfully authorized. */
  authcode?: string;
  /** The unique reference created by the brands/schemes to uniquely identify the transaction. */
  brandReference?: string;
  /** Masked card number with the front 6 and last 4 digits visible. */
  maskedNumberFirst6Last4?: string;
  /**
   * This is a code that identifies a specific card type and description that is returned when the
   * transaction is funded or being funded.
   */
  settlementCode?: string;
  /**
   * Indicates how the card is funded:
   *                            * `DEBIT` - indicates the card is a debit card where the funds may
   *                              be present in an account to fulfill the transaction amount.
   *                            * `CREDIT` - indicates the card is a credit card where the funds may
   *                              be available on credit to the payer to fulfill the transaction
   *                              amount.
   *                            * `FOOD_STAMP` - indicates the card is an, Electronic Benefits
   *                              Transfer, for food stamps.
   *                            * `CASH_BENEFITS` - indicates the card is an, Electronic Benefits
   *                              Transfer, for cash benefits.
   *                            * `PREPAID` - indicates the card is a prepaid card where the funds
   *                              are loaded to the card account to fulfill the transaction amount.
   *                              Unlike a debit card, a prepaid is not linked to a bank account.
   */
  funding?: FundingSettlementTransactionsPaymentMethodCardFunding;
  /**
   * ARN or Acquirer Reference Number is a Global Payments created reference sent to the card brands
   * to identify transactions. when a transfer of funds is initiated between Global Payments and the
   * card brands.
   */
  arn?: string;
  /** Properties the service sent or accepts beyond those declared. */
  additionalProperties?: Record<string, JsonValue>;
};

const cardListResponseProperties: s.Shape<CardListResponse> = {
  brand: s.optional(s.lazy(() => brandAuthenticationsPaymentMethodCardBrandSchema)),
  authcode: s.optional(s.string()),
  brandReference: s.optional(s.string()),
  maskedNumberFirst6Last4: s.optional(s.string()),
  settlementCode: s.optional(s.string()),
  funding: s.optional(s.lazy(() => fundingSettlementTransactionsPaymentMethodCardFundingSchema)),
  arn: s.optional(s.string()),
  _keysMap: {
    brandReference: "brand_reference",
    maskedNumberFirst6Last4: "masked_number_first6last4",
    settlementCode: "settlement_code",
  },
};

export const cardListResponseInternalSchema: Schema<CardListResponse> = s.object<CardListResponse>(
  cardListResponseProperties,
  { additionalProperties: s.json() },
);

export const cardListResponseSchema: Schema<CardListResponse> = s.lazySchema(() =>
  s.object<CardListResponse>(
    {
      ...cardListResponseProperties,
      authcode: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      brandReference: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      maskedNumberFirst6Last4: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      settlementCode: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
      arn: s.optional(s.string().check(s.minLength(1), s.maxLength(50))),
    },
    { additionalProperties: s.json() },
  ),
);
