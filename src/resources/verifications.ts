/**
 * Verifications represent the validation of a payment method to ensure it can be used in the
 * creation of a Transaction.
 */
export class Verifications {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * Verify
   *
   * @remarks
   * Verify a payment method to ensure it can be used to create a Transaction at a later time.
   *
   * @returns OK
   *
   * @throws {@link Verifications.CreateVerificationError} when the API answers with an error status
   * — narrow on `err.payload.kind`
   *
   * @throws {@link GlobalPaymentsApiError} when no usable response was produced: a connection
   * failure, a timeout, a body that would not decode, a value that would not encode, or a
   * credential that could not be obtained
   */
  createVerification(
    request: Verifications.CreateVerificationRequest,
    options?: RequestOptions,
  ): ApiPromise<CreateResponseVerifications, Verifications.CreateVerificationError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        urlTemplate: this.#servers.default("/verifications"),
        auth: this.#auth.bearerAuth,
        pathParams: [],
        query: [],
        headers: [
          { name: "X-GP-Version", value: request.xGpVersion, schema: s.defaulted(s.string(), "2021-03-22") },
          { name: "X-GP-Idempotency", value: request.xGpIdempotency, schema: s.optional(s.string()) },
          { name: "Idempotency-Key", value: uuid(), schema: s.string() },
        ],
        body: { kind: "json", value: request.body, schema: createRequestVerificationsInternalSchema },
      },
      {
        success: { kind: "json", schema: createResponseVerificationsInternalSchema },
        errorFactory: Verifications.CreateVerificationError,
      },
      options,
    );
  }
}

