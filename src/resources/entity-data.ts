/**
 * An entityData record is used to store a signature image for an entity's acceptance of terms and
 * conditions. This is stored in a separate table so as not to bloat the entities table with
 * signature images that use a lot of space. Additionally, the signatures are not included in API
 * requests for the entities themselves, instead they are requested separately via the entityDatas
 * resource.
 */
export class EntityData {
  readonly #rawClient: RawClient;
  readonly #servers: Servers;
  readonly #auth: AuthSchemes;

  constructor(rawClient: RawClient, servers: Servers, auth: AuthSchemes) {
    this.#rawClient = rawClient;
    this.#servers = servers;
    this.#auth = auth;
  }

  /**
   * getEntityDatas
   *
   * @remarks
   * Query an EntityDatas, which is the data related to an entity containing information about that
   * entity such as the signature for the terms and conditions.
   *
   * @returns Retrieve an Entity Data Response for the query on entityDatas resource.
   *
   * @throws {@link EntityData.GetEntityDatasError} when the API answers with an error status —
   * narrow on `err.payload.kind`
   *
   * @throws {@link PayrixError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  getEntityDatas(
    request: EntityData.GetEntityDatasRequest,
    options?: RequestOptions,
  ): ApiPromise<EntityDatasResponseResult, EntityData.GetEntityDatasError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        url: this.#servers.default("/entityDatas"),
        auth: anyAuth(this.#auth.apiKey, this.#auth.sessionKey, this.#auth.txnSessionKey),
        query: [
          { name: "page[number]", value: request.pageNumber, schema: s.optional(s.number()) },
          { name: "page[limit]", value: request.pageLimit, schema: s.optional(s.number()) },
          { name: "embed", value: request.embed, schema: s.optional(s.string()) },
        ],
        headers: [
          { name: "token", value: request.token, schema: s.optional(s.string()) },
          { name: "request-token", value: request.requestToken, schema: s.optional(s.string()) },
          { name: "search", value: request.search, schema: s.optional(s.string()) },
          { name: "totals", value: request.totals, schema: s.optional(s.string()) },
        ],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: entityDatasResponseResultSchema },
        errorFactory: EntityData.GetEntityDatasError,
      },
      options,
    );
  }

  /**
   * getEntityDatasId
   *
   * @remarks
   * Query an EntityDatas containing information about that entity, such as the signature for the
   * terms and conditions.
   *
   * @returns Retrieve an Entity Data Response for query on entityDatas resource.
   *
   * @throws {@link EntityData.GetEntityDatasIdError} when the API answers with an error status —
   * narrow on `err.payload.kind`
   *
   * @throws {@link PayrixError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  getEntityDatasId(
    request: EntityData.GetEntityDatasIdRequest,
    options?: RequestOptions,
  ): ApiPromise<EntityDatasResponseResult, EntityData.GetEntityDatasIdError> {
    return this.#rawClient.execute(
      {
        method: "GET",
        url: this.#servers.default("/entityDatas/{id}"),
        auth: anyAuth(this.#auth.apiKey, this.#auth.sessionKey, this.#auth.txnSessionKey),
        pathParams: [{ name: "id", value: request.id, schema: s.string() }],
        query: [{ name: "embed", value: request.embed, schema: s.optional(s.string()) }],
        headers: [
          { name: "token", value: request.token, schema: s.optional(s.string()) },
          { name: "request-token", value: request.requestToken, schema: s.optional(s.string()) },
        ],
        body: { kind: "empty" },
      },
      {
        success: { kind: "json", schema: entityDatasResponseResultSchema },
        errorFactory: EntityData.GetEntityDatasIdError,
      },
      options,
    );
  }

  /**
   * postEntityDatas
   *
   * @remarks
   * Create an EntityDatas containing the data related to an entity, including information such as
   * the signature for the terms and conditions.
   *
   * @returns The create on entityDatas response.
   *
   * @throws {@link EntityData.PostEntityDatasError} when the API answers with an error status —
   * narrow on `err.payload.kind`
   *
   * @throws {@link PayrixError} when no usable response was produced: a connection failure, a
   * timeout, a body that would not decode, a value that would not encode, or a credential that
   * could not be obtained
   */
  postEntityDatas(
    request: EntityData.PostEntityDatasRequest,
    options?: RequestOptions,
  ): ApiPromise<EntityDatasResponseResult, EntityData.PostEntityDatasError> {
    return this.#rawClient.execute(
      {
        method: "POST",
        url: this.#servers.default("/entityDatas"),
        auth: anyAuth(this.#auth.apiKey, this.#auth.sessionKey, this.#auth.txnSessionKey),
        headers: [
          { name: "token", value: request.token, schema: s.optional(s.string()) },
          { name: "request-token", value: request.requestToken, schema: s.optional(s.string()) },
          { name: "Idempotency-Key", value: uuid(), schema: s.string() },
        ],
        body: { kind: "json", value: request.body, schema: entityDataPostRequestSchema },
      },
      {
        success: { kind: "json", schema: entityDatasResponseResultSchema },
        errorFactory: EntityData.PostEntityDatasError,
      },
      options,
    );
  }
}

